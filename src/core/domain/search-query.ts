/**
 * تبدیل ورودی خام کاربر به عبارت امنِ FTS5 MATCH.
 *
 * نویسه‌های خاصِ نحوِ FTS5 (" * : ( ) و …) حذف می‌شوند تا هم از خطای نحوی و هم از
 * تزریق عملگر جلوگیری شود. سپس هر توکن با پیشوندمطابقت (`token*`) ساخته می‌شود تا
 * جست‌وجو با آغازِ واژه هم نتیجه بدهد. اگر چیزی باقی نماند، رشته‌ی خالی برمی‌گردد
 * (فراخوان باید آن را به‌عنوان «بدون نتیجه» تلقی کند).
 */
export function toFtsMatch(raw: string): string {
  const cleaned = raw
    .replace(/["*:()^\-~]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (cleaned.length === 0) return '';

  return cleaned
    .split(' ')
    .filter((t) => t.length > 0)
    .map((t) => `"${t}"*`)
    .join(' ');
}
